"""File storage behind an interface: a local folder in dev, an S3-compatible bucket in production.

Keys are always generated by us (`<project>/<kind>/<uuid>.<ext>`); user filenames are never used.
"""

import asyncio
import re
import uuid
from pathlib import Path
from typing import Any, Protocol

from renocore.settings import Settings, get_settings

_KEY_RE = re.compile(r"^[A-Za-z0-9_-]+(/[A-Za-z0-9_-]+)*\.[a-z0-9]{2,5}$")


def _check_key(key: str) -> str:
    if not _KEY_RE.match(key):
        raise ValueError(f"invalid storage key: {key!r}")
    return key


class Storage(Protocol):
    async def put(self, key: str, data: bytes) -> None: ...
    async def get(self, key: str) -> bytes: ...
    async def delete(self, key: str) -> None: ...
    async def exists(self, key: str) -> bool: ...


def new_key(prefix: str, ext: str) -> str:
    safe = "/".join(re.sub(r"[^A-Za-z0-9_-]", "_", p) for p in prefix.split("/") if p)
    return f"{safe}/{uuid.uuid4().hex}.{ext.lower().lstrip('.')}"


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / _check_key(key)).resolve()
        if self.root not in path.parents:
            raise ValueError(f"invalid storage key: {key!r}")
        return path

    async def put(self, key: str, data: bytes) -> None:
        path = self._path(key)

        def _write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            tmp = path.with_suffix(path.suffix + ".tmp")
            tmp.write_bytes(data)
            tmp.replace(path)

        await asyncio.to_thread(_write)

    async def get(self, key: str) -> bytes:
        return await asyncio.to_thread(self._path(key).read_bytes)

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self._path(key).unlink, True)

    async def exists(self, key: str) -> bool:
        return await asyncio.to_thread(self._path(key).exists)


class S3Storage:
    """Any S3-compatible bucket (Backblaze B2, Cloudflare R2, AWS S3, MinIO). Objects stay private;
    the API streams them to signed-in owners."""

    def __init__(self, client: Any, bucket: str) -> None:
        self.client = client
        self.bucket = bucket

    @classmethod
    def from_settings(cls, settings: Settings) -> "S3Storage":
        import boto3
        from botocore.config import Config

        client = boto3.client(
            "s3",
            endpoint_url=settings.s3_endpoint_url or None,
            region_name=settings.s3_region or None,
            aws_access_key_id=settings.s3_access_key_id,
            aws_secret_access_key=settings.s3_secret_access_key,
            config=Config(
                retries={"max_attempts": 5, "mode": "standard"},
                # not every S3-compatible service accepts the newer default checksums
                request_checksum_calculation="when_required",
                response_checksum_validation="when_required",
            ),
        )
        return cls(client, settings.s3_bucket)

    async def put(self, key: str, data: bytes) -> None:
        await asyncio.to_thread(
            self.client.put_object, Bucket=self.bucket, Key=_check_key(key), Body=data
        )

    async def get(self, key: str) -> bytes:
        def _read() -> bytes:
            obj = self.client.get_object(Bucket=self.bucket, Key=_check_key(key))
            return obj["Body"].read()

        return await asyncio.to_thread(_read)

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self.client.delete_object, Bucket=self.bucket, Key=_check_key(key))

    async def exists(self, key: str) -> bool:
        from botocore.exceptions import ClientError

        def _head() -> bool:
            try:
                self.client.head_object(Bucket=self.bucket, Key=_check_key(key))
            except ClientError as exc:
                if exc.response.get("Error", {}).get("Code") in ("404", "NoSuchKey", "NotFound"):
                    return False
                raise
            return True

        return await asyncio.to_thread(_head)


_storage: Storage | None = None


def get_storage() -> Storage:
    global _storage
    if _storage is None:
        settings = get_settings()
        if settings.storage_backend == "s3":
            _storage = S3Storage.from_settings(settings)
        else:
            _storage = LocalStorage(settings.storage_root)
    return _storage


def set_storage(storage: Storage | None) -> None:
    """Swap the storage backend (tests)."""
    global _storage
    _storage = storage
